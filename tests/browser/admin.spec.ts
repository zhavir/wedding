test('SQLAdmin credentials, record creation and sending action', async ({ page, browser }) => {
  test.skip(!process.env.ADMIN_TEST_CREDENTIALS, 'Run with Docker Compose to provision random local test credentials.');
  const credentials = adminCredentials();
  await page.goto('/admin');
  await expect(page).toHaveURL(/\/api\/admin\/login/);
  await page.getByLabel('Username').fill(credentials.username);
  await page.getByLabel('Password').fill(credentials.password);
  await page.getByLabel('Authenticator code').fill(authenticatorCode(credentials.secret));
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  if ((page.viewportSize()?.width ?? 1280) < 992) {
    await page.getByRole('button', { name: 'Toggle navigation' }).click();
  }
  await page.getByRole('link', { name: 'Invitations', exact: true }).click();
  const name = `Browser admin ${Date.now()}`;
  const email = `browser-admin-${Date.now()}@example.com`;
  await page.goto('/api/admin/guest/create');
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Language', { exact: true }).selectOption('it');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.goto('/api/admin/invitation/create');
  await page.getByLabel('Guest', { exact: true }).selectOption({ label: name });
  await page.getByLabel('Reserved places', { exact: true }).fill('2');
  await page.getByLabel('Active', { exact: true }).check();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: name });
  await expect(row).toContainText('draft');
  const invitationId = (await row.getByRole('link', { name: 'View', exact: true }).getAttribute('href'))!.split('/').pop();
  const preview = await page.request.get(`/api/admin/invitation/action/preview-email?pks=${invitationId}`);
  expect(preview.ok()).toBeTruthy();
  expect(await preview.text()).toContain('Siete invitati');
  const code = (await preview.text()).match(/[A-Z2-9]{5}-[A-Z2-9]{5}/)?.[0];
  expect(code).toBeTruthy();
  const guestContext = await browser.newContext({ baseURL: process.env.WEB_URL || 'http://localhost:5173' });
  const guestPage = await guestContext.newPage();
  await guestPage.goto('/#rsvp');
  await guestPage.getByLabel('Your invitation code').fill(code!);
  await guestPage.getByRole('button', { name: 'Open my invitation ↗' }).click();
  await guestPage.getByRole('button', { name: 'English', exact: true }).click();
  await expect(guestPage.getByLabel('Email address', { exact: true })).toHaveValue(email);
  await expect(guestPage.getByLabel('Full name').first()).toHaveValue(name);
  await guestPage.getByRole('link', { name: 'Upload your photos/videos ↗' }).click();
  await expect(guestPage.getByLabel('Choose photos and videos')).toBeVisible();
  await guestContext.close();
  await row.getByRole('checkbox').check();
  await page.getByRole('button', { name: /Actions/ }).click();
  await page.getByText('Send invitation', { exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review invitation emails' })).toBeVisible();
  await expect(page.getByText(name, { exact: false })).toContainText('draft');
  await page.getByRole('button', { name: 'Confirm and send emails' }).click();
  await expect(page.getByRole('heading', { name: 'Sending results' })).toBeVisible();
  await expect(page.locator('.card-body')).toContainText('sent');
  await page.getByRole('link', { name: 'Back to invitations' }).click();
  await expect(page.getByRole('row').filter({ hasText: name })).toContainText('sent');
});


